export type PasswordVerdict = "ok" | "too-short" | "too-long" | "common";

const MIN_LENGTH = 12;
const MAX_LENGTH = 128;

export function checkPassword(password: string): PasswordVerdict {
  if (password.length < MIN_LENGTH) return "too-short";
  if (password.length > MAX_LENGTH) return "too-long";
  if (COMMON_PASSWORDS.has(password.toLowerCase())) return "common";
  if (/^(.)\1+$/.test(password)) return "common";
  return "ok";
}
