import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { PasswordSetupForm } from "./PasswordSetupForm";

// Source: docs/specs/2026-11-10-access-control.md - "Password users" (Setup
// D22: the link is https://<host>/account/setup#<token>, the token in the URL
// fragment so it never reaches access logs; the page posts it to the Auth.js
// `password-setup` provider; an unknown, used or expired token gives one
// generic error. Passwords: 12-128 characters, no composition rules, rejected
// when in the common-password list. TOTP D23: enrolment is required for any
// role above internal-viewer or any admin scope, optional otherwise),
// threats T24 (token handling) and T25 ("the email is shown at setup").
// Design System: pages show loading and error states in place.
//
// Component contract (client component, components/auth/PasswordSetupForm.tsx):
//   <PasswordSetupForm
//     totpSecret={string}   // base32 secret generated by the page on the server
//     previewAction={(token) => Promise<{ email; displayName; totpRequired } | null>}
//     setupAction={(formData) => Promise<{ ok: false } | void>}  // success redirects
//   />
// The component reads the token from window.location.hash after mount (the
// fragment never reaches the server), calls previewAction(token) once, and
// submits FormData { token, password, totpSecret, totpCode } to setupAction;
// the token is never rendered, never put in a URL, link, form action or hidden
// input.
const TOKEN = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQ";
const SECRET = "JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP";
const EMAIL = "alice@example.com";
const GOOD = "correct horse battery staple";
const INVALID_LINK = /invalid or (has )?expired/i;

type Preview = { email: string; displayName: string; totpRequired: boolean };
const preview = (totpRequired = false): Preview => ({
  email: EMAIL,
  displayName: "Alice",
  totpRequired,
});

function setup(
  options: {
    preview?: Preview | null;
    setupResult?: { ok: false } | undefined;
  } = {},
) {
  const previewAction = vi.fn<(token: string) => Promise<Preview | null>>(
    async () => (options.preview === undefined ? preview() : options.preview),
  );
  const setupAction = vi.fn<
    (formData: FormData) => Promise<{ ok: false } | undefined>
  >(async () => options.setupResult);
  const view = render(
    <PasswordSetupForm
      totpSecret={SECRET}
      previewAction={previewAction}
      setupAction={setupAction}
    />,
  );
  return { previewAction, setupAction, ...view };
}

const newPassword = () => screen.findByLabelText(/^new password/i);
const confirmPassword = () => screen.findByLabelText(/^confirm new password/i);
const submit = () => screen.getByRole("button", { name: /^set password/i });

async function fill(user: ReturnType<typeof userEvent.setup>, password = GOOD) {
  await user.type(await newPassword(), password);
  await user.type(await confirmPassword(), password);
}

function sentForm(action: ReturnType<typeof vi.fn>): FormData {
  expect(action).toHaveBeenCalledTimes(1);
  return action.mock.calls[0]![0] as FormData;
}

beforeEach(() => {
  window.history.replaceState(null, "", `/account/setup#${TOKEN}`);
});
afterEach(() => {
  window.history.replaceState(null, "", "/");
});

describe("PasswordSetupForm - the link", () => {
  it("shows a loading status while the link is being checked, then the form", async () => {
    let release: (value: Preview) => void = () => {};
    const previewAction = vi.fn(
      () => new Promise<Preview>((resolve) => (release = resolve)),
    );
    render(
      <PasswordSetupForm
        totpSecret={SECRET}
        previewAction={previewAction}
        setupAction={vi.fn()}
      />,
    );
    expect(await screen.findByRole("status")).toHaveTextContent(/checking/i);
    expect(screen.queryByLabelText(/^new password/i)).toBeNull();
    release(preview());
    expect(await newPassword()).toBeInTheDocument();
    expect(screen.queryByRole("status")).toBeNull();
  });

  it("reads the token from the URL fragment and checks it exactly once", async () => {
    const { previewAction } = setup();
    await newPassword();
    expect(previewAction).toHaveBeenCalledTimes(1);
    expect(previewAction).toHaveBeenCalledWith(TOKEN);
  });

  it("shows the email the account is for, so a mistyped address is noticed (T25)", async () => {
    setup();
    await newPassword();
    expect(
      screen.getByText(new RegExp(EMAIL.replace(".", "\\."))),
    ).toBeVisible();
  });

  it("shows one generic invalid-link state, with no form, when the check answers null", async () => {
    setup({ preview: null });
    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent(INVALID_LINK);
    expect(alert).not.toHaveTextContent(
      /already used|disabled|deleted|locked/i,
    );
    expect(screen.queryByLabelText(/password/i)).toBeNull();
    expect(screen.queryByRole("button", { name: /set password/i })).toBeNull();
  });

  it.each([
    ["no fragment", ""],
    ["an empty fragment", "#"],
  ])(
    "shows the same invalid-link state, without calling the server, for %s",
    async (_name, hash) => {
      window.history.replaceState(null, "", `/account/setup${hash}`);
      const { previewAction } = setup();
      expect(await screen.findByRole("alert")).toHaveTextContent(INVALID_LINK);
      expect(previewAction).not.toHaveBeenCalled();
      expect(screen.queryByLabelText(/password/i)).toBeNull();
    },
  );

  it("never renders the token or puts it in a link, form action or hidden input", async () => {
    const { container } = setup();
    await newPassword();
    expect(container.innerHTML).not.toContain(TOKEN);
    expect(document.body.textContent).not.toContain(TOKEN);
    for (const el of container.querySelectorAll("[href], [action], [src]")) {
      for (const attr of ["href", "action", "src"]) {
        expect(el.getAttribute(attr) ?? "").not.toContain(TOKEN);
      }
    }
    for (const input of container.querySelectorAll("input")) {
      expect(input.value).not.toContain(TOKEN);
    }
    expect(window.location.search).toBe("");
  });

  it("does not render the token in the invalid-link state either", async () => {
    const { container } = setup({ preview: null });
    await screen.findByRole("alert");
    expect(container.innerHTML).not.toContain(TOKEN);
  });
});

describe("PasswordSetupForm - the form", () => {
  it("has labelled new-password and confirm fields that are password inputs for a password manager", async () => {
    setup();
    for (const field of [await newPassword(), await confirmPassword()]) {
      expect(field).toHaveAttribute("type", "password");
      expect(field).toHaveAttribute("autocomplete", "new-password");
      expect(field).toBeRequired();
    }
    expect(submit()).toHaveAttribute("type", "submit");
  });

  it("posts the token, the password and no TOTP when none is required or entered", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup();
    await fill(user);
    await user.click(submit());
    await waitFor(() => expect(setupAction).toHaveBeenCalledTimes(1));
    const form = sentForm(setupAction);
    expect(form.get("token")).toBe(TOKEN);
    expect(form.get("password")).toBe(GOOD);
    expect(form.get("totpCode") ?? "").toBe("");
  });

  it("posts a password of exactly 12 characters, with no composition rule", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup();
    await fill(user, "plum-otter-4");
    await user.click(submit());
    await waitFor(() => expect(setupAction).toHaveBeenCalledTimes(1));
    expect(sentForm(setupAction).get("password")).toBe("plum-otter-4");
  });

  it.each([
    ["is shorter than 12 characters", "short pw 1", /at least 12 characters/i],
    ["is in the common-password list", "password1234", /common/i],
  ])(
    "blocks a password that %s, with a message, before calling the server",
    async (_name, password, message) => {
      const user = userEvent.setup();
      const { setupAction } = setup();
      await fill(user, password);
      await user.click(submit());
      expect(await screen.findByRole("alert")).toHaveTextContent(message);
      expect(setupAction).not.toHaveBeenCalled();
    },
  );

  it("blocks a confirmation that does not match", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup();
    await user.type(await newPassword(), GOOD);
    await user.type(await confirmPassword(), `${GOOD}x`);
    await user.click(submit());
    expect(await screen.findByRole("alert")).toHaveTextContent(/do not match/i);
    expect(setupAction).not.toHaveBeenCalled();
  });

  it("shows the generic failure when the server refuses, without echoing the token or password", async () => {
    const user = userEvent.setup();
    const { setupAction, container } = setup({ setupResult: { ok: false } });
    await fill(user);
    await user.click(submit());
    const alert = await screen.findByRole("alert");
    expect(setupAction).toHaveBeenCalledTimes(1);
    expect(alert).toHaveTextContent(INVALID_LINK);
    expect(alert).not.toHaveTextContent(
      /already used|disabled|deleted|locked/i,
    );
    expect(container.innerHTML).not.toContain(TOKEN);
    expect(container.textContent).not.toContain(GOOD);
  });

  it("disables the submit button while the request is in flight, so the single-use link is not posted twice", async () => {
    const user = userEvent.setup();
    let release: () => void = () => {};
    const setupAction = vi.fn(
      () =>
        new Promise<undefined>(
          (resolve) => (release = () => resolve(undefined)),
        ),
    );
    render(
      <PasswordSetupForm
        totpSecret={SECRET}
        previewAction={async () => preview()}
        setupAction={setupAction}
      />,
    );
    await fill(user);
    await user.click(submit());
    await waitFor(() =>
      expect(
        screen.getByRole("button", { name: /(set|setting) password/i }),
      ).toBeDisabled(),
    );
    await user.click(
      screen.getByRole("button", { name: /(set|setting) password/i }),
    );
    expect(setupAction).toHaveBeenCalledTimes(1);
    release();
  });
});

describe("PasswordSetupForm - authenticator enrolment (D23)", () => {
  it("shows the secret for manual entry and requires a 6-digit code when TOTP is required", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup({ preview: preview(true) });
    await fill(user);
    expect(screen.getByText(SECRET)).toBeVisible();
    const code = screen.getByLabelText(/^authenticator code/i);
    expect(code).toBeRequired();

    await user.click(submit());
    expect(await screen.findByRole("alert")).toHaveTextContent(/6-digit code/i);
    expect(setupAction).not.toHaveBeenCalled();

    await user.type(code, "12345");
    await user.click(submit());
    expect(await screen.findByRole("alert")).toHaveTextContent(/6-digit code/i);
    expect(setupAction).not.toHaveBeenCalled();
  });

  it("posts the secret and the code together when TOTP is required", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup({ preview: preview(true) });
    await fill(user);
    await user.type(screen.getByLabelText(/^authenticator code/i), "123456");
    await user.click(submit());
    await waitFor(() => expect(setupAction).toHaveBeenCalledTimes(1));
    const form = sentForm(setupAction);
    expect(form.get("token")).toBe(TOKEN);
    expect(form.get("password")).toBe(GOOD);
    expect(form.get("totpSecret")).toBe(SECRET);
    expect(form.get("totpCode")).toBe("123456");
  });

  it("offers enrolment as optional when TOTP is not required, and posts it only when a code is entered", async () => {
    const user = userEvent.setup();
    const { setupAction } = setup({ preview: preview(false) });
    await fill(user);
    const code = screen.getByLabelText(/^authenticator code/i);
    expect(code).not.toBeRequired();
    await user.type(code, "654321");
    await user.click(submit());
    await waitFor(() => expect(setupAction).toHaveBeenCalledTimes(1));
    const form = sentForm(setupAction);
    expect(form.get("totpSecret")).toBe(SECRET);
    expect(form.get("totpCode")).toBe("654321");
  });

  it("keeps the secret out of the invalid-link state", async () => {
    const { container } = setup({ preview: null });
    await screen.findByRole("alert");
    expect(container.innerHTML).not.toContain(SECRET);
  });
});
